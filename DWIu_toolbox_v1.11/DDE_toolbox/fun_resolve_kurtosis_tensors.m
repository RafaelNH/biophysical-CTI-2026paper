function [DT, KT, KTi, KTv] = fun_resolve_kurtosis_tensors(pars)

DT =  pars(:, :, :, 2:7);
KT = pars(:, :, :, 8:22);
ZT = pars(:, :, :, 23:43);

MD2 = (mean(pars(:, :, :, 2:4), 4)) .^ 2;

KTv = KT;

KTv(:, :, :, 1) = 3*ZT(:, :, :, 1) ./ MD2;
KTv(:, :, :, 2) = 3*ZT(:, :, :, 2) ./ MD2;
KTv(:, :, :, 3) = 3*ZT(:, :, :, 3) ./ MD2;
KTv(:, :, :, 4) = 3*ZT(:, :, :, 4) ./ MD2;
KTv(:, :, :, 5) = 3*ZT(:, :, :, 5) ./ MD2;
KTv(:, :, :, 6) = 3*ZT(:, :, :, 6) ./ MD2;
KTv(:, :, :, 7) = 3*ZT(:, :, :, 7) ./ MD2;
KTv(:, :, :, 8) = 3*ZT(:, :, :, 8) ./ MD2;
KTv(:, :, :, 9) = 3*ZT(:, :, :, 9) ./ MD2;
KTv(:, :, :, 10) = (ZT(:, :, :, 10) + 2*ZT(:, :, :, 16)) ./ MD2;
KTv(:, :, :, 11) = (ZT(:, :, :, 11) + 2*ZT(:, :, :, 17)) ./ MD2;
KTv(:, :, :, 12) = (ZT(:, :, :, 12) + 2*ZT(:, :, :, 18)) ./ MD2;
KTv(:, :, :, 13) = (ZT(:, :, :, 13) + 2*ZT(:, :, :, 21)) ./ MD2;
KTv(:, :, :, 14) = (ZT(:, :, :, 14) + 2*ZT(:, :, :, 19)) ./ MD2;
KTv(:, :, :, 15) = (ZT(:, :, :, 15) + 2*ZT(:, :, :, 20)) ./ MD2;

KTi = KT - KTv;



